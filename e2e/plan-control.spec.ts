import { expect, test } from '@playwright/test'

test('build around the current tool survives detail visits and refresh', async ({ page }) => {
    await page.goto('/?tool=timing#counter')
    await page.getByRole('button', { name: 'Build around Timing', exact: true }).click()
    await expect(page.locator('.rx-name').nth(2)).toHaveText('Timing')
    expect(new URL(page.url()).searchParams.get('anchor')).toBe('timing')
    await expect(page.locator('.rx-plan-title')).toBeFocused()
    const names = await page.locator('.rx-name').allTextContents()
    await page.locator('.rx-name').nth(2).click()
    await page.getByRole('link', { name: 'Back to the cabinet', exact: true }).click()
    await expect.poll(() => page.locator('.rx-name').allTextContents()).toEqual(names)
    expect(new URL(page.url()).searchParams.get('anchor')).toBe('timing')
    await page.reload()
    await expect.poll(() => page.locator('.rx-name').allTextContents()).toEqual(names)
})

test('undo restores the exact previous seed, pinned rows and anchor after additional swaps', async ({ page }) => {
    await page.goto('/?plan=k4x9f2&anchor=timing&p=..paper-shaders#prescription')
    await expect(page.locator('.rx-name').nth(2)).toHaveText('Paper Shaders')
    const previous = await page.locator('.rx-name').allTextContents()
    await page.getByRole('button', { name: 'Write a new one', exact: true }).click()
    expect(new URL(page.url()).searchParams.has('anchor')).toBe(false)
    await page.getByRole('button', { name: /Swap the Make it move line/ }).click()
    await page.getByRole('button', { name: 'Restore previous prescription', exact: true }).click()
    await expect.poll(() => page.locator('.rx-name').allTextContents()).toEqual(previous)
    const restored = new URL(page.url())
    expect(restored.searchParams.get('plan')).toBe('k4x9f2')
    expect(restored.searchParams.get('anchor')).toBe('timing')
    expect(restored.searchParams.get('p')).toBe('..paper-shaders')
    await expect(page.getByRole('button', { name: 'Restore previous prescription', exact: true })).toHaveCount(0)
    await expect(page.locator('.rx-plan-title')).toBeFocused()
})

test('undo is one level and the advertised reload boundary clears it', async ({ page }) => {
    await page.goto('/?plan=k4x9f2#prescription')
    await page.getByRole('button', { name: 'Write a new one', exact: true }).click()
    const latestPreviousSeed = new URL(page.url()).searchParams.get('plan')
    const latestPrevious = await page.locator('.rx-name').allTextContents()
    await page.getByRole('button', { name: 'Write a new one', exact: true }).click()
    await page.getByRole('button', { name: 'Restore previous prescription', exact: true }).click()
    expect(new URL(page.url()).searchParams.get('plan')).toBe(latestPreviousSeed)
    await expect.poll(() => page.locator('.rx-name').allTextContents()).toEqual(latestPrevious)
    await page.getByRole('button', { name: 'Write a new one', exact: true }).click()
    await expect(page.getByRole('button', { name: 'Restore previous prescription', exact: true })).toBeVisible()
    await expect(page.locator('.rx-undo')).toContainText('reload')
    await page.reload()
    await expect(page.getByRole('button', { name: 'Restore previous prescription', exact: true })).toHaveCount(0)
})

test('anchored Markdown and copied links contain the reproducible direction', async ({ page }) => {
    await page.addInitScript(() => {
        Object.defineProperty(navigator, 'clipboard', { value: { writeText: () => Promise.reject(new Error('Denied')) } })
    })
    await page.goto('/?plan=k4x9f2&anchor=timing#prescription')
    await page.getByRole('button', { name: 'Copy as Markdown', exact: true }).click()
    const fallback = page.locator('.rx-slip .manual-copy textarea')
    await expect(fallback).toBeVisible()
    expect(await fallback.inputValue()).toContain('anchor=timing')
    expect(await fallback.inputValue()).toContain('returnTo=')
    await page.getByRole('button', { name: 'Copy link', exact: true }).click()
    const copied = new URL(await fallback.inputValue())
    expect(copied.searchParams.get('anchor')).toBe('timing')
    expect(copied.searchParams.get('plan')).toBe('k4x9f2')
})

test('selection announcements are concise and do not wrap interactive actions', async ({ page }) => {
    await page.goto('/?tool=timing#counter')
    await expect(page.locator('.counter')).not.toHaveAttribute('aria-live')
    await expect(page.locator('.counter [role="status"], .counter [aria-live]')).toHaveCount(0)
    await expect(page.locator('#counter-status')).toContainText('Timing')
    await expect(page.locator('.counter')).toHaveAccessibleName('Timing')
    await page.getByRole('button', { name: 'Next drawer', exact: true }).focus()
    await page.keyboard.press('ArrowRight')
    const current = (await page.locator('.slip-name').textContent()) ?? ''
    await expect(page.locator('#counter-status')).toContainText(current)
    await expect(page.locator('#counter-status')).toContainText('drawer C')
})

